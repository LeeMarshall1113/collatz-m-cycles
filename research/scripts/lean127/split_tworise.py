"""Split a generated MCycleTwoRise<m>.lean (chunks tr<N>_j of TwoRise.rangeOK, one huge module) into
checkpointed modules MCycleTwoRise<m>P<i>.lean of at most PER chunks each, and rewrite
MCycleTwoRise<m>.lean as their join (same final name TwoRise.allPairs<N>).

Why: one module holding all 803 chunks of AllPairs 97951 grew to 6.5 GB and slowed to a crawl
(killed after 6.7 h); 90 chunks build in 157 s at < 2.2 GB, 180-270 chunks again reach 6 GB and stall.
usage: python split_tworise.py m PER     (the original is kept as MCycleTwoRise<m>.orig)"""
import os, re, sys, shutil
m, PER = int(sys.argv[1]), int(sys.argv[2])
C = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Collatz')
p = os.path.join(C, f"MCycleTwoRise{m}.lean")
orig = p.replace(".lean", ".orig")
if not os.path.exists(orig):
    shutil.copy(p, orig)
src = open(orig, encoding="utf-8").read()
thms = re.findall(r"(theorem tr(\d+)_(\d+) : rangeOK \d+ (\d+) \d+ \d+ \(\(2 \^ \(\d+ \+ 1\) \+ 1\) / 3\) (\d+) (?:1|\(powMod [^\n]*?\)) (\d+) = true := by\n  decide \+kernel\n)", src)
N = int(thms[0][1]); B = int(thms[0][3])
ch = [(int(j), int(k), int(cnt), t) for t, _, j, _, k, cnt in thms]
ch.sort()
assert [c[0] for c in ch] == list(range(len(ch)))
assert ch[0][1] == 1 and all(ch[i][1] + ch[i][2] == ch[i + 1][1] for i in range(len(ch) - 1)) and ch[-1][1] + ch[-1][2] == N + 1
parts = [ch[i:i + PER] for i in range(0, len(ch), PER)]
for pi, part in enumerate(parts, 1):
    lo, hi = part[0][1], part[-1][1] + part[-1][2]
    L = [f"import Collatz.TwoRiseCheck\n\n/-!\n# `AllPairs {N} {B}`: first rises {lo}..{hi - 1} (part {pi} of {len(parts)})\n\n"
         f"Chunks of `MCycleTwoRise{m}.orig` (generated by `research/scripts/mcycle109/tworise.py`), split by\n"
         f"`research/scripts/lean127/split_tworise.py {m} {PER}` so that no module holds more than {PER} kernel checks.\n-/\n\n"
         "set_option Elab.async false\n\nnamespace Collatz.TwoRise\n\n"]
    for (_, _, _, t) in part:
        L.append(t + "\n")
    prev = None
    for (j, k, cnt, _) in part:
        nm = f"rc{N}_p{pi}_{j}"
        body = f"rangeOK_sound tr{N}_{j}" if prev is None else f"({prev}).trans (rangeOK_sound tr{N}_{j})"
        L.append(f"theorem {nm} : RangeCond {N} {B} {lo} {k + cnt} :=\n  {body}\n\n")
        prev = nm
    L.append(f"theorem rc{N}_part{pi} : RangeCond {N} {B} {lo} {hi} := {prev}\n\nend Collatz.TwoRise\n")
    open(os.path.join(C, f"MCycleTwoRise{m}P{pi}.lean"), "w", encoding="utf-8").write("".join(L))
J = "".join(f"import Collatz.MCycleTwoRise{m}P{pi}\n" for pi in range(1, len(parts) + 1))
J += (f"\n/-!\n# Two-rise bound `AllPairs {N} {B}` (kernel check, {len(ch)} chunks in {len(parts)} modules)\n-/\n\n"
      "namespace Collatz.TwoRise\n\n")
rc = f"rc{N}_part1"
for pi in range(2, len(parts) + 1):
    rc = f"({rc}).trans rc{N}_part{pi}"
J += f"theorem allPairs{N} : AllPairs {N} {B} := allPairs_of_range ({rc})\n\nend Collatz.TwoRise\n"
open(p, "w", encoding="utf-8").write(J)
print(f"m={m} N={N} B={B} chunks={len(ch)} parts={len(parts)}")
