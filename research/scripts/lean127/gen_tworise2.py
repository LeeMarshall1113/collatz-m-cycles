"""Emit the AllPairs N B kernel check with the linear-time checker TwoRise2.rangeOK2 (Collatz/TwoRiseCheck2.lean).

usage: python gen_tworise2.py N B CNT PER_MODULE [OUTDIR]
  Modules Collatz/TwoRise2_<N>_<i>.lean (i = 1..), each with PER_MODULE chunk theorems of CNT first rises
  (downwards: chunk k covers [k + 1 - cnt, k]) and one lemma `rc<N>_<i> : RangeCond N B lo hi`;
  Collatz/TwoRise2_<N>.lean joins them into `TwoRise2.allPairs<N> : TwoRise.AllPairs N B`.
  E1 = B - N + 6 (so lmin = 5), W = 2N + 2E1 + 64 (even)."""
import os, sys
N, B, CNT, PER = map(int, sys.argv[1:5])
OUT = sys.argv[5] if len(sys.argv) > 5 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'Collatz')
E1 = B - N + 6
W = 2 * N + 2 * E1 + 64; W += W % 2
i3 = f"((2 ^ ({W} + 1) + 1) / 3)"
chunks = []          # (k, cnt): covers [k+1-cnt, k]
k = 0
while k < N:
    cnt = min(CNT, N - k); k += cnt; chunks.append((k, cnt))
mods = [chunks[i:i + PER] for i in range(0, len(chunks), PER)]
names = []
for mi, mc in enumerate(mods, 1):
    nm = f"TwoRise2_{N}_{mi}"; names.append((nm, mc[0][0] + 1 - mc[0][1], mc[-1][0] + 1))
    L = [f"import Collatz.TwoRiseCheck2\n\n/-!\n# `AllPairs {N} {B}`, first rises {mc[0][0] + 1 - mc[0][1]}..{mc[-1][0]} (part {mi} of {len(mods)})\n\n"
         f"Generated by `research/scripts/lean127/gen_tworise2.py {N} {B} {CNT} {PER}`; `E₁ = {E1}`, `W = {W}`.\n-/\n\n"
         "set_option Elab.async false\n\nnamespace Collatz.TwoRise2\n\nopen Collatz.TwoRise\n"]
    for (kk, cnt) in mc:
        L.append(f"\ntheorem t{N}_{kk} : rangeOK2 {N} {B} {E1} {W} {kk} {cnt} (powLo {W} 64 {i3} {kk} 1) = true := by\n  decide +kernel\n")
    rc = f"(rangeOK2_sound t{N}_{mc[0][0]})"
    for (kk, cnt) in mc[1:]:
        rc = f"(RangeCond.trans {rc} (rangeOK2_sound t{N}_{kk}))"
    L.append(f"\ntheorem rc{N}_{mi} : RangeCond {N} {B} {names[-1][1]} {names[-1][2]} :=\n  {rc}\n\nend Collatz.TwoRise2\n")
    open(os.path.join(OUT, nm + ".lean"), "w", encoding="utf-8").write("".join(L))
J = [f"{''.join(f'import Collatz.{nm}' + chr(10) for nm, _, _ in names)}\n/-!\n# `AllPairs {N} {B}` (linear-time checker, {len(chunks)} chunks in {len(names)} modules)\n-/\n\n"
     "namespace Collatz.TwoRise2\n\nopen Collatz.TwoRise\n\n"]
rc = f"rc{N}_1"
for i in range(2, len(names) + 1):
    rc = f"(RangeCond.trans {rc} rc{N}_{i})"
J.append(f"theorem allPairs{N} : AllPairs {N} {B} := allPairs_of_range {rc}\n\nend Collatz.TwoRise2\n")
open(os.path.join(OUT, f"TwoRise2_{N}.lean"), "w", encoding="utf-8").write("".join(J))
print(f"N={N} B={B} E1={E1} W={W} chunks={len(chunks)} modules={len(names)}")
