"""Emit the AllTriples kernel-check modules for new B3 grid points, split into independent parts.

MCycleThreeRiseN<N>[_<j>].lean proves `RangeCond3 N B lo hi` for a range of first rises (parts are
independent, so lake can build them side by side), and the grid module joins them with
`RangeCond3.trans` into `AllTriples N B`."""
import os

TRIPLES_PER_CHUNK = int(os.environ.get("TRIPLES_PER_CHUNK", "8000"))
NL = "\n"


def W3(N, B, E1):
    return 2 * B + 2 * E1 + 64


def units_of(N, B, E1):
    """kernel-check units: ('range', k0, cnt) over whole first rises, or ('split', k0, [(l, cnt)], hi)
    for a first rise with more than TRIPLES_PER_CHUNK triples (cost per l0 ~ hi - l0 values of k1)."""
    W = W3(N, B, E1)
    units, k, acc, start = [], 1, 0, 1
    while k <= N:
        cst = max(1, (N - k) ** 2 // 2)
        if cst > TRIPLES_PER_CHUNK:
            assert start == k
            A = N - k if k < N else 1
            c0 = pow(3, -k, 2 ** W)
            x = c0 >> A
            t = (x & -x).bit_length() - 1
            hi = A + t + 1
            pieces, l, a2 = [], 1, 0
            for l0 in range(1, hi):
                a2 += max(1, hi - l0)
                if a2 >= TRIPLES_PER_CHUNK or l0 == hi - 1:
                    pieces.append((l, l0 + 1 - l)); l, a2 = l0 + 1, 0
            units.append(('split', k, pieces, hi, cst))
            k += 1; start = k
            continue
        acc += cst
        if acc >= TRIPLES_PER_CHUNK or k == N or max(1, (N - k - 1) ** 2 // 2) > TRIPLES_PER_CHUNK:
            units.append(('range', start, k + 1 - start, acc)); start, acc = k + 1, 0
        k += 1
    return units


def part_modules(out, N, B, E1, nparts, tag):
    """write the part modules of AllTriples N B; return [(module, last rt name, lo, hi)]"""
    W = W3(N, B, E1)
    i3 = f"((2 ^ ({W} + 1) + 1) / 3)"
    us = units_of(N, B, E1)
    cost = [u[-1] for u in us]
    tot, parts, cur, acc = sum(cost), [], [], 0
    for j in range(len(us)):
        cur.append(j)
        acc += cost[j]
        if acc >= tot * (len(parts) + 1) / nparts and len(parts) < nparts - 1:
            parts.append(cur)
            cur = []
    if cur:
        parts.append(cur)
    names = []
    for pi, js in enumerate(parts):
        nm = f"MCycleThreeRiseN{N}" + (f"_{pi + 1}" if len(parts) > 1 else "")
        lo = us[js[0]][1]
        L = ["import Collatz.ThreeRiseSplit", "",
             "/-!", f"# Three-rise bound `AllTriples {N} {B}`, part {pi + 1} of {len(parts)}", "",
             f"Generated by `research/scripts/{tag}`: `rangeOK3` (whole first rises) and `lRangeOK3`",
             "(one first rise in `ℓ₀` pieces) evaluated by the kernel. The parts are independent; the grid",
             "module joins them.", "-/", "", "set_option Elab.async false", "", "namespace Collatz.ThreeRise", ""]
        prev = None
        for j in js:
            u = us[j]
            if u[0] == 'range':
                _, k0, cnt, _ = u
                c0 = "1" if k0 == 1 else f"(TwoRise.powMod (2 ^ {W}) 64 {i3} {k0 - 1} 1)"
                L += [f"theorem tt{N}_{j} : rangeOK3 {N} {B} {E1} {W} {i3} {k0} {c0} {cnt} = true := by",
                      "  decide +kernel", ""]
                step = f"rangeOK3_sound tt{N}_{j}"
                hi = k0 + cnt
            else:
                _, k0, pieces, lhi, _ = u
                C = f"(TwoRise.powMod (2 ^ {W}) 64 {i3} {k0} 1)"
                lp = None
                for q, (l, cnt) in enumerate(pieces):
                    L += [f"theorem ls{N}_{k0}_{q} : lRangeOK3 {N} {B} {E1} {W} {i3} {k0} {C} {l} {cnt} = true := by",
                          "  decide +kernel", ""]
                    if lp is None:
                        L += [f"theorem lr{N}_{k0}_{q} : LRange3 {N} {B} {k0} 1 {l + cnt} := lRangeOK3_sound ls{N}_{k0}_{q}", ""]
                    else:
                        L += [f"theorem lr{N}_{k0}_{q} : LRange3 {N} {B} {k0} 1 {l + cnt} :=",
                              f"  ({lp}).trans (lRangeOK3_sound ls{N}_{k0}_{q})", ""]
                    lp = f"lr{N}_{k0}_{q}"
                assert pieces[-1][0] + pieces[-1][1] == lhi
                L += [f"theorem tc{N}_{k0} : TripleCond {N} {B} {k0} :=",
                      f"  tripleCond_of_lRange (W := {W}) (c0 := {C}) (by decide +kernel) {lp}", ""]
                step = f"rangeCond3_single tc{N}_{k0}"
                hi = k0 + 1
            if prev is None:
                L += [f"theorem rt{N}_{j} : RangeCond3 {N} {B} {lo} {hi} := {step}", ""]
            else:
                L += [f"theorem rt{N}_{j} : RangeCond3 {N} {B} {lo} {hi} :=", f"  ({prev}).trans ({step})", ""]
            prev = f"rt{N}_{j}"
        L += ["end Collatz.ThreeRise", ""]
        open(os.path.join(out, nm + ".lean"), "w", encoding="utf-8").write(NL.join(L))
        names.append((nm, prev, lo, hi))
    assert names[0][2] == 1 and names[-1][3] == N + 1
    for (_, _, _, h), (_, _, l, _) in zip(names, names[1:]):
        assert h == l
    print("B3", N, B, "units", len(us), "split k0", sum(u[0] == 'split' for u in us),
          "decls", sum(1 if u[0] == 'range' else len(u[2]) + 1 for u in us),
          "parts", [(n, lo, hi) for n, _, lo, hi in names], flush=True)
    return names


def grid_module(out, gname, modname, grid, old_imports, joins, title):
    """grid module: joins parts into AllTriples, defines gname and gname_ok"""
    L = ["import Collatz.MCycleSteps3"] + [f"import Collatz.{i}" for i in old_imports]
    L += [f"import Collatz.{n}" for N in joins for n, _, _, _ in joins[N]]
    L += ["", "/-!", f"# {title}", "", "Generated; the `AllTriples` of the new points are joined from their parts here.",
          "-/", "", "namespace Collatz", ""]
    for N, B in grid:
        if N not in joins:
            continue
        pf = f"ThreeRise.{joins[N][0][1]}"
        for _, r, _, _ in joins[N][1:]:
            pf = f"({pf}).trans ThreeRise.{r}"
        L += [f"/-- `k₀ + k₁ + k₂ ≤ {B}` for the first three rises from every odd `n < 2^{N}`. -/",
              f"theorem ThreeRise.allTriples{N} : ThreeRise.AllTriples {N} {B} :=",
              f"  ThreeRise.allTriples_of_range ({pf})", ""]
    g = ", ".join(f"({N}, {B})" for N, B in grid)
    L += [f"/-- The three-rise bounds `(N, B)` (increasing `N`). -/", f"def {gname} : List (ℕ × ℕ) := [{g}]", "",
          f"theorem {gname}_ok : ∀ e ∈ {gname}, ThreeRiseBound e.1 e.2 := by", "  intro e h"]
    for N, _ in grid:
        L += ["  rcases List.mem_cons.mp h with h | h",
              f"  · rw [h]; exact threeRiseBound_of_allTriples ThreeRise.allTriples{N}"]
    L += ["  · cases h", "", "end Collatz", ""]
    open(os.path.join(out, modname + ".lean"), "w", encoding="utf-8").write(NL.join(L))
