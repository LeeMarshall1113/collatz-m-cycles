"""Emit MCycleTwoRise<m>.lean (AllPairs N B, linear lemma chain) and MCycleGrid<m>.lean for the new B2 points.
usage: python tworise.py OUTDIR   (108: 97951/97965 ; 109: 151960/151978)"""
import os, sys, re, subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'mcycle101_certgen'))
import gen_lean as L
out = sys.argv[1]
PTS = {108: (97951, 97965), 109: (151960, 151978)}
for m, (N, B) in PTS.items():
    p = os.path.join(out, f"MCycleTwoRise{m}.lean")
    with open(p, "w", encoding="utf-8") as f:
        f.write("import Collatz.TwoRiseCheck\n\n/-!\n# Two-rise bound `AllPairs %d %d` (kernel check)\n\n"
                "Generated by `research/scripts/mcycle109/tworise.py` (`gen_lean.tworise_lean`, chunked `rangeOK`,\n"
                "joined as a linear chain of lemmas `rc%d_j`; see `mcycle103_split/linear_chain.py`).\n-/\n\n"
                "set_option Elab.async false\n\nnamespace Collatz.TwoRise\n\n" % (N, B, N))
        f.write(L.tworise_lean(N, B) + "\nend Collatz.TwoRise\n")
    subprocess.check_call([sys.executable, os.path.join(HERE, '..', 'mcycle103_split', 'linear_chain.py'), p])
    prev = "MCycleGrid103" if m == 108 else "MCycleGrid108"
    pg = "grid103" if m == 108 else "grid108"
    prevpts = [] if m == 108 else [PTS[108]]
    with open(os.path.join(out, f"MCycleGrid{m}.lean"), "w", encoding="utf-8") as f:
        f.write(f"import Collatz.{prev}\nimport Collatz.MCycleTwoRise{m}\n\n/-!\n# Two-rise grid `grid{m}`: `{pg}` and the new point `{N}`\n-/\n\nnamespace Collatz\n\n"
                f"/-- The two-rise bounds `(N, B)` (increasing `N`). -/\ndef grid{m} : List (ℕ × ℕ) := {pg} ++ [({N}, {B})]\n\n"
                f"theorem grid{m}_ok : ∀ e ∈ grid{m}, TwoRiseBound e.1 e.2 := by\n"
                f"  intro e h\n  unfold grid{m} at h\n  rcases List.mem_append.mp h with h | h\n"
                f"  · exact {pg}_ok e h\n"
                f"  · rcases List.mem_singleton.mp h with rfl\n    exact twoRiseBound_of_allPairs TwoRise.allPairs{N}\n\nend Collatz\n")
