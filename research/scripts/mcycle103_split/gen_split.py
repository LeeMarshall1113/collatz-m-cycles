"""Emit MCycle103Def.lean, MCycle103Walk<j>.lean, MCycle103Data.lean: the m = 103 certificate with the
Farey walk evaluated in pieces (Collatz/WalkSplit.lean).
usage: gen_split.py TREE.pkl KEYS.pkl GENERATED_MCycle103.lean OUTDIR STEPS_PER_MODULE [MAXMODULES]"""
import pickle, sys, os, re
T = pickle.load(open(sys.argv[1], "rb")); nodes = T['nodes']; root = T['root']
keys = pickle.load(open(sys.argv[2], "rb"))
gen = open(sys.argv[3], encoding="utf-8").read()
out = sys.argv[4]; per = int(sys.argv[5]); maxmods = int(sys.argv[6]) if len(sys.argv) > 6 else 10**9
assert keys[-1]['i'] == root
W = "walk data103.pairs data103.Kceil data103.Ks"
IMP = "(st := data103.pairs) (Kc := data103.Kceil) (Km := data103.Ks)"
def lit(sh):
    return "([] : List (ℕ × ℕ))" if not sh else "[" + ", ".join(f"({k}, {p})" for k, p in sh) + "]"
def lhs(i):
    n = nodes[i]; a, b, c, d = n['abcd']
    return f"{W} {n['fuel']} {a} {b} {c} {d}"
def thm(k):
    i = k['i']; n = nodes[i]; F = n['fuel']; a, b, c, d = n['abcd']
    head = f"theorem w{i} : {lhs(i)} = {lit(n['sh'])} :="
    if k['t'] == 'stop':
        assert n['sh'] == []
        return f"{head}\n  walk_stop {IMP} {F - 1} (a := {a}) (c := {c}) (by decide +kernel)\n", 1
    if k['t'] == 'chain':
        j = k['to']; m = nodes[j]; a2, b2, c2, d2 = m['abcd']; s = k['n']
        assert m['fuel'] == F - s and m['sh'] == n['sh']
        return (f"{head}\n  (walk_wchain {IMP} {F - s} {s} (a := {a}) (b := {b}) (c := {c}) (d := {d})\n"
                f"    (a' := {a2}) (b' := {b2}) (c' := {c2}) (d' := {d2}) (by decide +kernel)).trans w{j}\n"), s
    l, r = k['l'], k['r']
    e, g = a + c, b + d
    assert nodes[l]['abcd'] == (a, b, e, g) and nodes[r]['abcd'] == (e, g, c, d)
    assert nodes[l]['fuel'] == F - 1 == nodes[r]['fuel']
    return (f"{head} by\n  rw [walk_mid {IMP} {F - 1} (a := {a}) (b := {b}) (c := {c}) (d := {d}) (e := {e}) (g := {g})\n"
            f"    (by decide +kernel) rfl rfl, w{l}, w{r}]\n  decide +kernel\n"), 1
# module 0: the definition
m = re.search(r"\ntheorem data103_ok", gen); assert m
defpart = gen[:m.start()]
defpart = defpart.replace("import Collatz.MCycleWalk\n", "import Collatz.MCycleWalk\nimport Collatz.WalkSplit\n", 1)
open(os.path.join(out, "MCycle103Def.lean"), "w", encoding="utf-8").write(defpart + "\nend Collatz\n")
mods, cur, cost = [], [], 0
for k in keys:
    t, c = thm(k)
    cur.append(t); cost += c
    if cost >= per:
        mods.append(cur); cur, cost = [], 0
if cur: mods.append(cur)
prev = "MCycle103Def"
names = []
for j, body in enumerate(mods[:maxmods]):
    nm = f"MCycle103Walk{j + 1}"
    with open(os.path.join(out, nm + ".lean"), "w", encoding="utf-8") as f:
        f.write(f"import Collatz.{prev}\n\n/-!\n# The Farey walk of `data103`, part {j + 1} of {len(mods)}\n\n"
                f"Generated by `gen_split.py`: `walk` at the nodes of this part, from the parts before it\n"
                f"(`WalkSplit.lean`); each `decide +kernel` evaluates one node or one run of single steps.\n-/\n\n"
                f"set_option Elab.async false\n\nnamespace Collatz\n\n")
        f.write("\n".join(body))
        f.write("\nend Collatz\n")
    prev = nm; names.append(nm)
print("modules", len(mods), "written", len(names), "keys", len(keys))
CH = int(os.environ.get("CERT_CHUNK", "5")); QM = int(os.environ.get("CERT_PER_MOD", "4"))
if len(names) == len(mods):
    sh = nodes[root]['sh']
    chunks = [sh[x:x + CH] for x in range(0, len(sh), CH)]
    nm = "MCycle103Shapes"
    with open(os.path.join(out, nm + ".lean"), "w", encoding="utf-8") as f:
        f.write(f"import Collatz.{prev}\n\n/-!\n# The listed shapes of `data103`, from the walk pieces, in chunks of {CH}\n-/\n\n"
                f"namespace Collatz\n\n/-- The listed shapes (the value of `data103.shapes`). -/\n"
                f"def shapes103 : List (ℕ × ℕ) := {lit(sh)}\n\n"
                f"theorem data103_shapes : data103.shapes = shapes103 := w{root}\n\n")
        for j, c in enumerate(chunks):
            f.write(f"def shapes103_{j} : List (ℕ × ℕ) := {lit(c)}\n\n")
        cat = " ++ ".join(f"shapes103_{j}" for j in range(len(chunks)))
        f.write(f"theorem shapes103_split : shapes103 = {cat} := by\n  decide +kernel\n\nend Collatz\n")
    prev = nm
    cmods = []
    for q in range(0, len(chunks), QM):
        cm = f"MCycle103Certs{q // QM + 1}"
        with open(os.path.join(out, cm + ".lean"), "w", encoding="utf-8") as f:
            f.write(f"import Collatz.{prev}\n\n/-!\n# Certificates of the listed shapes of `data103`, chunks {q}..{min(q + QM, len(chunks)) - 1}\n-/\n\n"
                    f"set_option Elab.async false\n\nnamespace Collatz\n\n")
            for j in range(q, min(q + QM, len(chunks))):
                f.write(f"theorem certs103_{j} : certsOK 103 20 grid103 data103.certs shapes103_{j} = true := by\n  decide +kernel\n\n")
            f.write("end Collatz\n")
        prev = cm; cmods.append(cm)
    tail = gen[m.start():]
    simps = ", ".join(f"certs103_{j}" for j in range(len(chunks)))
    tail = tail.replace("theorem data103_ok : mOK 103 20 grid103 data103 = true := by\n  decide +kernel\n",
        f"/-- The certificate check of all listed shapes, from the chunks. -/\n"
        f"theorem certs103 : certsOK 103 20 grid103 data103.certs shapes103 = true := by\n"
        f"  rw [shapes103_split]\n  simp only [certsOK_append, {simps}, Bool.and_self]\n\n"
        f"theorem data103_ok : mOK 103 20 grid103 data103 = true := by\n"
        f"  unfold mOK\n  rw [data103_shapes, certs103, Bool.and_true]\n  decide +kernel\n")
    assert "certs103" in tail
    with open(os.path.join(out, "MCycle103Data.lean"), "w", encoding="utf-8") as f:
        f.write(f"import Collatz.{prev}\n\n/-!\n# No Collatz 103-cycle when every `n ≤ 2⁷¹` reaches 1\n\n"
                f"`data103` is in `MCycle103Def.lean`. Its walk is evaluated in pieces in `MCycle103Walk1..{len(mods)}`\n"
                f"(`WalkSplit.lean`) and the certificates of the listed shapes in `MCycle103Certs1..{len(cmods)}`;\n"
                f"`data103_ok` assembles them into Alick's `mOK` check.\n-/\n\n"
                f"namespace Collatz\n" + tail)
    print("cert chunks", len(chunks), "cert modules", len(cmods))
