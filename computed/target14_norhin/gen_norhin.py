"""Generate Collatz/NoRhin.lean: the m <= 111 chain with EffMeasure in place of RhinBound.
Copies the RhinBound-dependent soundness theorems and top-level chain verbatim, renamed *_eff,
with the single Rhin step (K_lt_of_rhinOK) replaced by K_lt_of_ceilOK and a kernel ceilOK check."""
import re, pathlib
R = pathlib.Path(__file__).resolve().parents[2] / 'Collatz'
def rd(f): return (R / f).read_text(encoding='utf8')
def block(src, name):
    i = src.index('theorem ' + name + ' ')
    # include preceding docstring
    j = src.rfind('/--', 0, i)
    if j != -1 and src[j:i].count('-/') == 1 and src[src.index('-/', j)+2:i].strip() == '':
        i = j
    k = src.find('\n\n', i)
    k2 = src.find('\nend Collatz', i)
    k = min(x for x in (k, k2) if x != -1)
    return src[i:k].rstrip() + '\n'
def sound(src, name):
    b = block(src, name)
    b = b.replace('theorem ' + name + ' (hR : RhinBound)', 'theorem ' + name + '_eff (hE : EffMeasure)')
    b = re.sub(r'(\(hok : mOK\w* [^)]*= true\))', r'\1 (hceil : ceilOK m D.Kceil = true)', b, count=1)
    assert 'hceil' in b
    old = 'have hKc := K_lt_of_rhinOK hR hx hp hcyc hx1 hx2 hm hrhin'
    assert old in b
    b = b.replace(old, 'have hKc := K_lt_of_ceilOK hE hx hp hcyc hm hceil')
    b = b.replace('given `RhinBound`', 'given `EffMeasure`')
    assert 'hR' not in b and 'RhinBound' not in b, b
    return b
def ren(b):
    b = re.sub(r'\b(no_\d+_cycle_2_71|no_\d+_cycle_of_floor|hercher_theorem_2_71|hercher_theorem|mOK_sound|mOK3_sound|mOK3D_sound)\b', r'\1_eff', b)
    b = b.replace('(hR : RhinBound)', '(hE : EffMeasure)').replace('`RhinBound`', '`EffMeasure`')
    b = re.sub(r'\bhR\b', 'hE', b)
    assert 'Rhin' not in b, b
    return b
out = []
out.append(sound(rd('MCycleWalk.lean'), 'mOK_sound'))
out.append(sound(rd('MCycleChain3.lean'), 'mOK3_sound'))
out.append(sound(rd('MCycleChain3D.lean'), 'mOK3D_sound'))
# m <= 91
out.append('''/-- The ceilings of Hercher's 91 entries from `EffMeasure`, one kernel check per `m`. -/
theorem hercherCeil_ok (m : ℕ) (h1 : 1 ≤ m) (h2 : m ≤ 91) :
    ceilOK m (hercherData.getD (m - 1) defaultEntry).Kf = true := by
  interval_cases m <;> decide +kernel
''')
hb = block(rd('HercherAll.lean'), 'hercher_theorem')
hb = hb.replace('have h2 := K_lt_of_rhinOK hR hx hp hcyc hx1 hx2 hm he.2',
                'have h2 := K_lt_of_ceilOK hE hx hp hcyc hm (hercherCeil_ok m (by omega) (by omega))')
assert 'K_lt_of_ceilOK' in hb
hb = hb.replace("Simons–de Weger's Lemma 12 (Rhin's transcendence measure) holds", '`EffMeasure` holds')
out.append(ren(hb))
floors = {}
for m in range(92, 112):
    for f in ['MCycle%d.lean' % m, 'MCycle%dData.lean' % m]:
        if (R / f).exists() and ('theorem no_%d_cycle_of_floor ' % m) in rd(f):
            b = block(rd(f), 'no_%d_cycle_of_floor' % m)
            b = re.sub(r'(data\d+_ok)', r'\1 (by decide +kernel)', b, count=1)
            out.append(ren(b))
            floors[m] = f
            break
    else:
        raise SystemExit('no floor theorem for %d' % m)
top = rd('MCycle101.lean')
for nm in ['hercher_theorem_2_71', 'no_92_cycle_2_71', 'no_94_cycle_2_71', 'no_96_cycle_2_71', 'no_101_cycle_2_71']:
    out.append(ren(block(top, nm)))
for m, nms in [(102, ['no_102_cycle_2_71']), (103, ['no_103_cycle_2_71']), (105, ['no_105_cycle_2_71']),
               (107, ['no_106_cycle_2_71', 'no_107_cycle_2_71']), (108, ['no_108_cycle_2_71']),
               (109, ['no_109_cycle_2_71']), (110, ['no_110_cycle_2_71']), (111, ['no_111_cycle_2_71'])]:
    for nm in nms:
        out.append(ren(block(rd('MCycle%d.lean' % m), nm)))
hdr = '''import Collatz
import Collatz.EffMeasure

/-!
# No Collatz `m`-cycle with `m ≤ 111`, from Bařina's `2⁷¹` and `EffMeasure` only

Generated by `computed/target14_norhin/gen_norhin.py` from the `RhinBound` chain: the three
soundness theorems (`mOK_sound`, `mOK3_sound`, `mOK3D_sound`), Hercher's theorem for `m ≤ 91`, the
per-`m` floor theorems and the `_2_71` chain, verbatim, renamed `*_eff`, with the one Rhin step
(`K_lt_of_rhinOK`, the ceiling `K < Kceil`) replaced by `K_lt_of_ceilOK` and a kernel check of
`ceilOK m Kceil`. The data and certificate checks (`dataN_ok`, `hercherData_ok`) are reused as they
are; they never involved `RhinBound`.
-/

set_option maxRecDepth 100000

namespace Collatz

'''
(R / 'NoRhin.lean').write_text(hdr + '\n'.join(out) + '\nend Collatz\n', encoding='utf8')
print('floors', floors)
